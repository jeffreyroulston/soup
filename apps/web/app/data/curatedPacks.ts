/** Hard-coded Soup collections: match against the library; hide when too few hits. */

export type CuratedPackEntry = {
  imdb?: string
  tmdb?: string
  name: string
  year?: number
  type?: 'Movie' | 'Series'
}

export type CuratedPackTheme = {
  bg: string
  accent: string
  mid: string
  label: string
}

export type CuratedPack = {
  id: string
  title: string
  description: string
  minMatches: number
  wave: 'a' | 'b' | 'c'
  /** Inclusive calendar window (local date). Omitted = always eligible. */
  season?: { startMonth: number, startDay: number, endMonth: number, endDay: number }
  theme: CuratedPackTheme
  entries: CuratedPackEntry[]
}

function m(imdb: string, name: string, year?: number): CuratedPackEntry {
  return { imdb, name, year, type: 'Movie' }
}

function s(imdb: string, name: string, year?: number): CuratedPackEntry {
  return { imdb, name, year, type: 'Series' }
}

